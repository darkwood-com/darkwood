    public static function explodeSector(string $src, int $expectedSize): string
    {
        $out = self::explode($src, $expectedSize);
        if (strlen($out) > $expectedSize) {
            throw new \RuntimeException('PKWARE explode: output too large');
        }
        // Pad short last sectors? callers expect exact size for sector cache.
        if (strlen($out) < $expectedSize) {
            $out .= str_repeat("\0", $expectedSize - strlen($out));
        }

        return $out;
    }

    public static function explode(string $src, int $dstSize): string
    {
        $srcSize = strlen($src);
        if ($srcSize < 2) {
            throw new \RuntimeException('PKWARE explode: truncated input');
        }
        $compType = ord($src[0]);
        $dictBits = ord($src[1]);
        if ($compType > 1) {
            throw new \RuntimeException('PKWARE explode: bad literal type');
        }
        if ($dictBits < 4 || $dictBits > 6) {
            throw new \RuntimeException('PKWARE explode: bad dict size');
        }

        $data = substr($src, 2);
        $pos = 0;
        $size = strlen($data);
        $bits = 0;
        $avail = 0;
        $out = '';

        $fill = function (int $need) use (&$data, &$pos, &$size, &$bits, &$avail): bool {
            while ($avail < $need) {
                if ($pos >= $size) {
                    return false;
                }
                $bits |= ord($data[$pos++]) << $avail;
                $avail += 8;
            }

            return true;
        };
        $peek = function (int $n) use (&$bits): int {
            return $bits & ((1 << $n) - 1);
        };
        $drop = function (int $n) use (&$bits, &$avail): void {
            $bits >>= $n;
            $avail -= $n;
        };
        $read = function (int $n) use ($fill, $peek, $drop): int {
            if ($n === 0) {
                return 0;
            }
            if (!$fill($n)) {
                return -1;
            }
            $val = $peek($n);
            $drop($n);

            return $val;
        };

        $decodeDist = function () use ($fill, $peek, $drop): int {
            if (!$fill(8)) {
                return -1;
            }
            $p = $peek(8);
            for ($i = 0; $i < 64; $i++) {
                $nbits = self::DIST_BITS[$i];
                $mask = (1 << $nbits) - 1;
                if (($p & $mask) === self::DIST_CODE[$i]) {
                    $drop($nbits);

                    return $i;
                }
            }

            return -1;
        };
        $decodeLen = function () use ($fill, $peek, $drop): int {
            if (!$fill(7)) {
                return -1;
            }
            $p = $peek(7);
            for ($i = 0; $i < 16; $i++) {
                $nbits = self::LEN_BITS[$i];
                $mask = (1 << $nbits) - 1;
                if (($p & $mask) === self::LEN_CODE[$i]) {
                    $drop($nbits);

                    return $i;
                }
            }

            return -1;
        };
        $decodeAscii = function () use ($fill, &$bits, &$avail, $drop): int {
            $fill(13);
            $p = $bits;
            for ($i = 0; $i < 256; $i++) {
                $nbits = self::ASCII_BITS[$i];
                if ($nbits === 0 || $avail < $nbits) {
                    continue;
                }
                $mask = (1 << $nbits) - 1;
                if (($p & $mask) === self::ASCII_CODE[$i]) {
                    $drop($nbits);

                    return $i;
                }
            }

            return -1;
        };

        while (strlen($out) < $dstSize) {
            $flag = $read(1);
            if ($flag === -1) {
                break;
            }
            if ($flag === 0) {
                if ($compType === 1) {
                    $ch = $decodeAscii();
                } else {
                    $ch = $read(8);
                }
                if ($ch < 0) {
                    throw new \RuntimeException('PKWARE explode: bad literal');
                }
                $out .= chr($ch);
            } else {
                $lenIdx = $decodeLen();
                if ($lenIdx < 0) {
                    throw new \RuntimeException('PKWARE explode: bad length');
                }
                $exBits = self::EX_LEN_BITS[$lenIdx];
                $extra = 0;
                if ($exBits !== 0) {
                    $extra = $read($exBits);
                    if ($extra === -1) {
                        throw new \RuntimeException('PKWARE explode: truncated length');
                    }
                }
                if ($lenIdx === 15 && $extra === 0xFF) {
                    break;
                }
                $matchLen = self::LEN_BASE[$lenIdx] + $extra + 2;
                $distIdx = $decodeDist();
                if ($distIdx < 0) {
                    throw new \RuntimeException('PKWARE explode: bad distance');
                }
                if ($matchLen === 2) {
                    $lo = $read(2);
                    if ($lo === -1) {
                        throw new \RuntimeException('PKWARE explode: truncated dist');
                    }
                    $dist = ($distIdx << 2) | $lo;
                } else {
                    $lo = $read($dictBits);
                    if ($lo === -1) {
                        throw new \RuntimeException('PKWARE explode: truncated dist');
                    }
                    $dist = ($distIdx << $dictBits) | $lo;
                }
                $outPos = strlen($out);
                if ($dist + 1 > $outPos) {
                    throw new \RuntimeException('PKWARE explode: distance OOB');
                }
                $copyFrom = $outPos - $dist - 1;
                for ($i = 0; $i < $matchLen; $i++) {
                    $out .= $out[$copyFrom + $i];
                }
            }
        }

        return $out;
    }
