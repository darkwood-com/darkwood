#!/usr/bin/env python3
"""Generate godot/native/state/routed_port.gd: every Original port function (pacific_conflict.gd)
that native_overlay.gd does not write by hand, verbatim except `memory.` -> `_routed.`
(routed_memory.gd: the Native blocks and Godot-owned records to Godot, everything else to the Mac
memory). A function native_overlay.gd wraps (it calls routed_<name>) is emitted as routed_<name>.
Same statements, same order, same callees and a7. --check
fails when the file is not what the current Original source (and the hand-written list) gives.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "godot/original/port/pacific_conflict.gd"
TARGET = ROOT / "godot/native/state/routed_port.gd"
NATIVE = ROOT / "godot/native/state/native_overlay.gd"

HEADER = '''extends "res://original/port/pacific_conflict.gd"

## GENERATED by tools/native/gen_routed_port.py from original/port/pacific_conflict.gd: do not
## edit. The Original's camera readers and writers, each verbatim except `memory.` -> `_routed.`:
## the Native blocks (camera angles 0x1d800..0x1d811, position 0x1d830..0x1d83b, view state\n## 0x1d856..0x1d859) are read and written in
## native_block.gd (Godot-backed for Native), everything else in the Mac memory as before.
## native_overlay.gd extends this script.

const NativeBlock := preload("res://native/state/native_block.gd")
const RoutedMemory := preload("res://native/state/routed_memory.gd")
const NativeRecords := preload("res://native/state/native_records.gd")

## Rollback switches: true keeps the block in Godot; false in the Mac memory (the reference).
var camera_angle_storage_godot := true
var camera_position_storage_godot := true
var view_state_storage_godot := true
var record_storage_godot := true
var _records = null
var _camera_angles = null
var _camera_position = null
var _view_state = null
var _routed_memory = null

func camera_angles():
	if _camera_angles == null:
		_camera_angles = NativeBlock.new(memory, NativeBlock.CAMERA_ANGLES, camera_angle_storage_godot)
	return _camera_angles

func camera_position():
	if _camera_position == null:
		_camera_position = NativeBlock.new(memory, NativeBlock.CAMERA_POSITION, camera_position_storage_godot)
	return _camera_position

func view_state():
	if _view_state == null:
		_view_state = NativeBlock.new(memory, NativeBlock.VIEW_STATE, view_state_storage_godot)
	return _view_state

## The Godot-backed blocks.
func native_blocks() -> Array:
	return [camera_angles(), camera_position(), view_state()].filter(func(b) -> bool: return b.godot_backed)

## The Godot-owned heap records (null when record_storage_godot is off: the Mac memory, reference).
func records():
	if _records == null and record_storage_godot:
		_records = NativeRecords.new(memory)
	return _records

## The latest Native overlay's routed view, for host code that reads the overlay in place
## (host_routed_memory.gd).
static var active_router = null

var _routed:
	get:
		if _routed_memory == null:
			_routed_memory = RoutedMemory.new(memory, [camera_angles(), camera_position(), view_state()], records())
			active_router = _routed_memory
		return _routed_memory
'''


def extract(lines, name):
    start = next(i for i, l in enumerate(lines) if l.startswith("func %s(" % name))
    # The body: indented or blank lines; the first top-level line (comment, const, var, func) ends it.
    end = next((i for i in range(start + 1, len(lines)) if lines[i] and not lines[i].startswith("\t")), len(lines))
    body = lines[start:end]
    # Drop the next function's leading comment and blank lines.
    while body and (body[-1].startswith("##") or body[-1].strip() == ""):
        body.pop()
    return start + 1, body


def hand_written():
    return set(re.findall(r"^func (\w+)\(", NATIVE.read_text(), re.M))


def wrapped():
    """Functions native_overlay.gd wraps: it calls routed_<name>(...), emitted here under that name."""
    return set(re.findall(r"\brouted_(\w+)\(", NATIVE.read_text()))


def generate():
    lines = SOURCE.read_text().split("\n")
    names = [m.group(1) for m in (re.match(r"func (\w+)\(", l) for l in lines) if m]
    skip = hand_written()
    wrap = wrapped()
    out = [HEADER]
    count = 0
    for name in names:
        if name == "_init" or (name in skip and name not in wrap):
            continue
        line, body = extract(lines, name)
        if name in skip:
            body[0] = body[0].replace("func %s(" % name, "func routed_%s(" % name, 1)
        text = "\n".join(body)
        routed = re.sub(r"\bmemory\.", "_routed.", text)
        out.append("\n# pacific_conflict.gd:%d %s\n%s\n" % (line, name, routed))
        count += 1
    return "\n".join(out), count


def main():
    text, count = generate()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            print("FAIL routed port: %s is not what %s gives (run tools/native/gen_routed_port.py)" % (TARGET.relative_to(ROOT), SOURCE.relative_to(ROOT)))
            return 1
        print("PASS routed port: %d functions generated from the Original" % count)
        return 0
    TARGET.write_text(text)
    print("wrote %s (%d functions)" % (TARGET.relative_to(ROOT), count))
    return 0


if __name__ == "__main__":
    sys.exit(main())
